// New arrivals: products with badge 'New', topped up with the most recently added products
export const getNewArrivals = () => {
  const newBadge = products.filter(p => p.badge === 'New');
  if (newBadge.length >= 8) return newBadge.slice(0, 8);
  // Fill remaining slots from the tail of the products array (most recently added)
  const rest = products.filter(p => p.badge !== 'New').slice(-8);
  return [...newBadge, ...rest].slice(0, 8);
};

